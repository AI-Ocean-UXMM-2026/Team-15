export type Lang = "en" | "my";
export const copy: Record<Lang, Record<TextKey, string>> = { en, my };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const table = copy[lang] || en;
  const template = (table as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) => (vars[name] !== undefined ? String(vars[name]) : `{${name}}`));
}

/** Database stores English category names; this gives the translation key for one. */
export const categoryKey = (category: string) => `cat_${String(category || "Other").replace(/[^A-Za-z]/g, "")}`;

/** Show numbers with Myanmar digits when the UI is in Burmese. */
export function formatNumber(lang: Lang, n: number | string): string {
  const s = typeof n === "number" ? n.toLocaleString("en-US") : String(n);
  return lang === "my" ? s.replace(/[0-9]/g, (d) => "၀၁၂၃၄၅၆၇၈၉"[Number(d)]) : s;
}
